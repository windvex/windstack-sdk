import { execFileSync } from "node:child_process";
import { readFile } from "node:fs/promises";
import { extname } from "node:path";

const TEXT_EXTENSIONS = new Set([
  ".cjs",
  ".js",
  ".json",
  ".md",
  ".mjs",
  ".ts",
  ".tsx",
  ".yaml",
  ".yml",
]);

const forbidden = [
  ["chat", "gpt"].join(""),
  ["open", "ai"].join(""),
  ["co", "dex"].join(""),
  ["ai", "-generated"].join(""),
  ["generated by ", "ai"].join(""),
  ["implementation ", "diary"].join(""),
  ["remaining ", "work"].join(""),
  ["0–100% ", "rollout"].join(""),
  ["work", "around"].join(""),
  ["compatibility ", "helper"].join(""),
  ["check", "point"].join(""),
  ["re", "factor"].join(""),
];

const files = execFileSync("git", ["ls-files"], { encoding: "utf8" })
  .split("\n")
  .map((value) => value.trim())
  .filter(Boolean)
  .filter((file) => TEXT_EXTENSIONS.has(extname(file).toLowerCase()));

const violations = [];
for (const file of files) {
  const content = (await readFile(file, "utf8")).toLowerCase();
  for (const marker of forbidden) {
    if (content.includes(marker)) violations.push(`${file}: ${marker}`);
  }
}

if (violations.length) {
  console.error("Public-content release guard failed:");
  for (const violation of violations) console.error(`- ${violation}`);
  process.exit(1);
}

console.log(`Public-content release guard passed (${files.length} tracked text files).`);
